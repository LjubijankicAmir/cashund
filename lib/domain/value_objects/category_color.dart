/// The colors a category can have, by name and in picker order.
///
/// Only the name is stored; the theme decides the actual shade for light and
/// dark, so a tweak to the palette updates every category.
enum CategoryColor {
  coral,
  sky,
  mustard,
  plum,
  olive,
  periwinkle,
  apricot,
  teal,
  rose,
  slate,
  lavender,
  cocoa,
}
